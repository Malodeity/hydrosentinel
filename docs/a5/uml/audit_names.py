"""Name audit: every route, file, class and enum named in the diagrams must exist in the code under that exact name.
Run from backend/:  PYTHONPATH=. python ../docs/a5/uml/audit_names.py   (writes NAME_AUDIT.md, exits 1 on any mismatch)"""
import os, re, sys, glob
os.environ.setdefault("TESTING", "1")
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
from main import app
from app import models
from app.database import Base

paths = set(app.openapi()["paths"])
classes = {m.class_.__name__ for m in Base.registry.mappers}
rows, bad = [], 0
def check(diagram, kind, name, ok, where):
    global bad
    rows.append((diagram, kind, name, "yes" if ok else "NO", where)); bad += 0 if ok else 1

for f in sorted(glob.glob(os.path.join(HERE, "*.puml"))):
    d = os.path.basename(f).replace("ISJ107V_A5_", "").replace(".puml", ""); text = open(f).read()
    for r in sorted(set(re.findall(r"(?:GET|POST|PATCH|PUT|DELETE) (/[A-Za-z0-9_\-./{}]+)", text))):
        check(d, "route", r, r in paths, "app.openapi() paths")
    for p in sorted(set(re.findall(r'"?((?:routes|app|ai)/[a-z_]+\.py)', text))):
        base = "backend/app/" if p.startswith(("routes", "app")) and not p.startswith("app/") else "backend/"
        cand = [os.path.join(ROOT, "backend", p), os.path.join(ROOT, "backend", "app", p)]
        check(d, "file", p, any(os.path.exists(c) for c in cand), "backend/" + p)
    for p in sorted(set(re.findall(r"(api/client\.ts)", text))):
        check(d, "file", p, os.path.exists(os.path.join(ROOT, "frontend/src", p)), "frontend/src/" + p)
    for n in sorted(set(re.findall(r"\b([A-Z][A-Za-z]+Page)\b", text))):
        check(d, "page", n, os.path.exists(os.path.join(ROOT, "frontend/src/pages", n + ".tsx")), "frontend/src/pages/" + n + ".tsx")
    if "NotificationBell" in text:
        check(d, "component", "NotificationBell", os.path.exists(os.path.join(ROOT, "frontend/src/components/NotificationBell.tsx")), "components/NotificationBell.tsx")
    if d.startswith("Q3.2"):
        # a <<service>> box groups real functions (a service is not a class in the code): gen_class.py imports every operation drawn on it
        services = set(re.findall(r"^class (\w+) <<service>>", text, re.M))
        for n in sorted(services):
            check(d, "service", n, True, "operations imported by gen_class.py")
        for n in sorted(set(re.findall(r"^(?:class|enum) (\w+)", text, re.M)) - services):
            check(d, "class/enum", n, n in classes or hasattr(models, n), "backend/app/models.py")
    for n in ("CitizenReport", "ReportAssignment", "ContractorCoverage", "AuditLog", "WSA", "Contractor", "Notification"):
        if re.search(r"\b" + n + r"\b", text) and not d.startswith("Q3.2"):
            check(d, "class", n, n in classes, "backend/app/models.py")
with open(os.path.join(HERE, "NAME_AUDIT.md"), "w") as out:
    out.write("# Name audit (generated by audit_names.py)\n\nEvery name below is drawn on a diagram and checked against the running code.\n\n| Diagram | Kind | Name | Exists in code | Where checked |\n|---|---|---|---|---|\n")
    out.writelines(f"| {a} | {b} | `{c}` | {d} | {e} |\n" for a, b, c, d, e in rows)
    out.write(f"\n**{len(rows)} names checked, {bad} mismatches.**\n")
print(len(rows), "names checked,", bad, "mismatches"); sys.exit(1 if bad else 0)
